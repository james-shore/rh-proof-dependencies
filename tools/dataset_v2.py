#!/usr/bin/env python3
"""Dataset v0.2: declarations and file/line from the compiled environment (route B), spans = the source command.
Usage: dataset_v2.py V013_DIR ROUTEB_MAP DECL_INDEX MIRROR OUT
  V013_DIR: dataset v0.1.3 (constants.parquet, edges.parquet) — kernel-side columns are kept as they are
  ROUTEB_MAP: routeb-constants-mapped.tsv (routeb_map.py): every project constant -> declaration + compiled range
  DECL_INDEX: decl-index.tsv.gz (decl_index.py), used only for command spans (top-level command segmentation)
A declaration = a top-level constant with its own compiled declaration range (Lean's unit). Its span is the top-level
source command containing the first line of its compiled range (docstring, attributes and `... in` lines included); if
no indexed command contains it (e.g. a lemma made by an `attribute [...]` command), the span is the compiled range."""
import bisect, collections, gzip, json, os, sys
import duckdb

V013, RBMAP, IDX, MIRROR, OUT = sys.argv[1:6]
os.makedirs(OUT, exist_ok=True)
con = duckdb.connect()
con.execute(f"SET threads TO {int(os.environ.get('THREADS', '8'))}; SET memory_limit = '200GB'; SET preserve_insertion_order = false")
TSV = "delim='\\t', header=true, quote='', escape='', all_varchar=true"

# ---------- source: line counts and top-level command spans ----------
import time as _t
_T0 = _t.time()
def say(*a):
    print(f'[{_t.time() - _T0:7.0f}s]', *a, file=sys.stderr, flush=True)
file_lines = {}
for root, _, files in os.walk(os.path.join(MIRROR, 'src')):
    for fn in files:
        if fn.endswith('.lean'):
            rel = os.path.relpath(os.path.join(root, fn), MIRROR)
            if rel != 'src/Challenge.lean':
                with open(os.path.join(root, fn), 'rb') as f:
                    file_lines[rel] = f.read().count(b'\n')
cmds = collections.defaultdict(list)  # file -> sorted [(start, end, kind)]
with gzip.open(IDX, 'rt', encoding='utf-8') as f:
    h = f.readline().rstrip('\n').split('\t'); H = {x: i for i, x in enumerate(h)}
    for line in f:
        r = line.rstrip('\n').split('\t')
        if r[H['parent']] or r[H['file']] == 'src/Challenge.lean':
            continue
        cmds[r[H['file']]].append((int(r[H['start_line']]), int(r[H['end_line']]), r[H['kind']]))
for v in cmds.values():
    v.sort()
cstarts = {k: [x[0] for x in v] for k, v in cmds.items()}
def command_of(file, line):
    v = cmds.get(file)
    if not v:
        return None
    i = bisect.bisect_right(cstarts[file], line) - 1
    if i >= 0 and v[i][0] <= line <= v[i][1]:
        return v[i]
    return None

say('text index loaded')
# ---------- kernel side from v0.1.3 ----------
con.execute(f"CREATE TABLE k AS SELECT * FROM read_parquet('{V013}/constants.parquet')")
kd = {r[0]: (r[1], r[2]) for r in con.execute("SELECT name, depth, in_cone FROM k WHERE origin = 'project'").fetchall()}

say('kernel side loaded')
# ---------- route B mapping ----------
own = {}            # decl -> (kind, module, file, range start, range end)
const_rows = []     # (name, decl, rule, shared, module)
with open(RBMAP) as f:
    h = f.readline().rstrip('\n').split('\t'); H = {x: i for i, x in enumerate(h)}
    for line in f:
        r = line.rstrip('\n').split('\t')
        name, decl, rule = r[H['name']], r[H['decl']], r[H['rule']]
        if decl and rule == 'self':
            own[decl] = (r[H['kind']], r[H['module']], r[H['file']], int(r[H['start_line']]), int(r[H['end_line']]))
        if name in kd:  # constant is in the export
            const_rows.append((name, decl, rule, r[H['shared_aux']] == '1', r[H['module']]))
# per declaration: constants, in-cone (own non-shared constants), depth
nconst = collections.Counter(); ncone = collections.Counter(); nshared = collections.Counter(); ddepth = {}
for name, decl, rule, shared, mod in const_rows:
    if not decl:
        continue
    depth, incone = kd[name]
    nconst[decl] += 1
    if incone and shared:
        nshared[decl] += 1
    elif incone:
        ncone[decl] += 1
        ddepth[decl] = min(ddepth.get(decl, 1 << 30), depth)
say('mapping read')
# spans
span = {}
no_command = 0
for d, (kind, mod, file, rs, re_) in own.items():
    c = command_of(file, rs)
    if c is None:
        span[d] = (rs, re_, '(compiled range)')
        no_command += 1
    else:
        span[d] = (c[0], c[1], c[2])
say('spans done')
# ---------- decls table ----------
# compile-time definitions generated by notation/macro/elab commands: needed to compile, never in proof terms; they get
# their own flag and stay out of the declaration counts (unit: declarations a person wrote)
GENERATED = {'notation', 'notation3', 'macro', 'macro_rules', 'elab', 'elab_rules', 'syntax', 'infix', 'infixl', 'infixr',
             'prefix', 'postfix', 'unif_hint', 'run_cmd', 'custom_cmd', 'example'}
rows = []
cmd_decls = collections.Counter()
for d in own:
    cmd_decls[(own[d][2], span[d][0])] += 1
for d, (kind, mod, file, rs, re_) in own.items():
    s, e, ck = span[d]
    rows.append((d, kind, ck, 'project', mod, file, s, e, e - s + 1, rs, re_, nconst[d], ncone[d], nshared[d],
                 ncone[d] > 0, ddepth.get(d, -1), cmd_decls[(file, s)], ck in GENERATED))
def load(table, cols, data):
    tmp = os.path.join(OUT, f'.{table}.tsv')
    with open(tmp, 'w') as f:
        for r in data:
            f.write('\t'.join('' if v is None else str(v) for v in r) + '\n')
    types = ', '.join(f"'{c}': '{t}'" for c, t in cols)
    con.execute(f"CREATE TABLE {table} AS SELECT * FROM read_csv('{tmp}', delim='\\t', header=false, quote='', escape='', "
                f"nullstr='', columns={{{types}}})")
    os.remove(tmp)
load('decls', [('decl', 'VARCHAR'), ('kind', 'VARCHAR'), ('command_kind', 'VARCHAR'), ('origin', 'VARCHAR'), ('module', 'VARCHAR'),
               ('file', 'VARCHAR'), ('start_line', 'INTEGER'), ('end_line', 'INTEGER'), ('lines', 'INTEGER'),
               ('range_start_line', 'INTEGER'), ('range_end_line', 'INTEGER'), ('n_constants', 'INTEGER'),
               ('n_constants_in_cone', 'INTEGER'), ('n_shared_aux_in_cone', 'INTEGER'), ('in_cone', 'BOOLEAN'),
               ('depth', 'INTEGER'), ('decls_in_command', 'INTEGER'), ('generated', 'BOOLEAN')], rows)
con.execute("ALTER TABLE decls ADD COLUMN source VARCHAR DEFAULT 'routeB-env'")
say('decls loaded')
# ---------- constants table: project columns from route B ----------
load('rb', [('name', 'VARCHAR'), ('decl', 'VARCHAR'), ('rule', 'VARCHAR'), ('shared', 'BOOLEAN'), ('module', 'VARCHAR')],
     [(a, b or None, c, d, e) for a, b, c, d, e in const_rows])
con.execute("CREATE TABLE ds AS SELECT decl, file, start_line, end_line, range_start_line, range_end_line FROM decls")
con.execute("""CREATE TABLE constants AS SELECT k.id, k.name, k.kind,
  k.origin, CASE WHEN k.origin = 'project' THEN rb.module ELSE k.module END AS module,
  k.nlevels, k.type_dag, k.value_dag, k.type_tree, k.value_tree, k.refs_type, k.refs_value, k.in_cone, k.in_export, k.depth,
  k.thm_mask, k.block, k.record,
  CASE WHEN k.origin = 'project' THEN rb.decl ELSE k.decl END AS decl,
  CASE WHEN k.origin = 'project' THEN rb.rule ELSE k.aux_rule END AS aux_rule,
  NULL::VARCHAR AS map_note,
  CASE WHEN k.origin = 'project' THEN COALESCE(rb.shared, false) ELSE k.shared_aux END AS shared_aux,
  ds.file, ds.start_line, ds.end_line,
  CASE WHEN k.origin = 'project' THEN 'routeB-env' ELSE k.source END AS source, k.info,
  ds.range_start_line, ds.range_end_line
  FROM k LEFT JOIN rb ON rb.name = k.name LEFT JOIN ds ON ds.decl = rb.decl AND k.origin = 'project'""")
say('constants table built')
# ---------- directories (lines = union of command spans) ----------
def dkeys(file):
    parts = file.split('/')
    ks = [('/'.join(parts[:2]), 1)]
    if len(parts) > 3:
        ks.append(('/'.join(parts[:3]), 2))
    return ks
dirs = collections.defaultdict(collections.Counter)
dfiles = collections.defaultdict(set); dfiles_cone = collections.defaultdict(set)
spans_cone = collections.defaultdict(set); spans_all = collections.defaultdict(set)
for r in rows:
    d, file, s, e, incone = r[0], r[5], r[6], r[7], r[14]
    if r[17]:
        continue
    spans_all[file].add((s, e))
    if incone:
        spans_cone[file].add((s, e))
    for dk in dkeys(file):
        dirs[dk]['decls'] += 1
        dirs[dk]['decls_in_cone'] += incone
        if incone:
            dfiles_cone[dk].add(file)
def union_len(sp):
    tot = 0; cur = None
    for s, e in sorted(sp):
        if cur and s <= cur[1]:
            cur[1] = max(cur[1], e)
        else:
            if cur:
                tot += cur[1] - cur[0] + 1
            cur = [s, e]
    return tot + (cur[1] - cur[0] + 1 if cur else 0)
cone_lines_file = {f: union_len(sp) for f, sp in spans_cone.items()}
for file, n in file_lines.items():
    for dk in dkeys(file):
        dirs[dk]['lines'] += n
        dirs[dk]['files'] += 1
        dirs[dk]['lines_in_cone'] += cone_lines_file.get(file, 0)
drows = []
for (dk, lvl), c in sorted(dirs.items()):
    pd = 100.0 * c['decls_in_cone'] / c['decls'] if c['decls'] else 0.0
    pl = 100.0 * c['lines_in_cone'] / c['lines'] if c['lines'] else 0.0
    drows.append((dk, lvl, c['files'], c['files'], len(dfiles_cone[(dk, lvl)]), c['lines'], c['lines_in_cone'], c['decls'],
                  c['decls_in_cone'], round(pd, 2), round(pl, 2)))
load('directories', [('dir', 'VARCHAR'), ('level', 'INTEGER'), ('files', 'INTEGER'), ('files_in_import_closure', 'INTEGER'),
                     ('files_in_cone', 'INTEGER'), ('lines', 'INTEGER'), ('lines_in_cone', 'INTEGER'), ('decls', 'INTEGER'),
                     ('decls_in_cone', 'INTEGER'), ('pct_decls_used', 'DOUBLE'), ('pct_lines_used', 'DOUBLE')], drows)
say('directories done')
# ---------- keep list (command spans) ----------
keep = sorted((r for r in rows if r[14]), key=lambda r: (r[5], r[6], r[0]))
with open(os.path.join(OUT, 'keep-v2.tsv'), 'w') as f:
    f.write('decl\tkind\tfile\tstart_line\tend_line\tn_constants_in_cone\trange_start_line\trange_end_line\n')
    for r in keep:
        f.write(f'{r[0]}\t{r[1]}\t{r[5]}\t{r[6]}\t{r[7]}\t{r[12]}\t{r[9]}\t{r[10]}\n')
say('keep written')
# ---------- deterministic writes ----------
KEYS = {'constants': 'id', 'decls': 'file, start_line, range_start_line, decl', 'directories': 'level, dir'}
for t, k in KEYS.items():
    con.execute(f"CREATE TABLE {t}_sorted AS SELECT * FROM {t} ORDER BY {k}")
con.execute("SET threads TO 1; SET preserve_insertion_order = true")
for t in KEYS:
    con.execute(f"COPY {t}_sorted TO '{OUT}/{t}.parquet' (FORMAT parquet, COMPRESSION zstd, ROW_GROUP_SIZE 1000000)")
    con.execute(f"COPY {t}_sorted TO '{OUT}/{t}.csv.gz' (FORMAT csv, HEADER, COMPRESSION gzip)")
con.execute("SET threads TO 8")
say('tables written')
# ---------- stats ----------
incone_files = {r[5] for r in rows if r[14]}
ranges_cone = collections.defaultdict(set)
for r in rows:
    if r[14]:
        ranges_cone[r[5]].add((r[9], r[10]))
st = {
    'decls': sum(1 for r in rows if not r[17]), 'decls_in_cone': sum(1 for r in rows if r[14]),
    'generated_by_notation_macro_elab': sum(1 for r in rows if r[17]),
    'generated_in_cone': sum(1 for r in rows if r[17] and r[14]),
    'rows_total': len(rows),
    'decls_without_indexed_command': no_command,
    'commands_holding_several_decls': sum(1 for v in cmd_decls.values() if v > 1),
    'files_with_in_cone_decl': len(incone_files),
    'lines_total': sum(file_lines.values()),
    'lines_in_cone_command_spans': sum(cone_lines_file.values()),
    'lines_in_cone_compiled_ranges': sum(union_len(sp) for sp in ranges_cone.values()),
    'lines_in_any_decl_command_span': sum(union_len(sp) for sp in spans_all.values()),
    'project_constants_in_cone_mapped': con.execute("SELECT count(*) FROM constants WHERE origin = 'project' AND in_cone AND decl IS NOT NULL").fetchone()[0],
    'project_constants_in_cone': con.execute("SELECT count(*) FROM constants WHERE origin = 'project' AND in_cone").fetchone()[0],
}
json.dump(st, open(os.path.join(OUT, 'dataset-v2-stats.json'), 'w'), indent=1)
print(json.dumps(st, indent=1))
