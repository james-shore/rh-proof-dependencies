"""End-to-end test of dominators.py on a synthetic dataset with a known answer.

Graph (decls): the five theorems -> main; T3 -> t3only; main -> chapA, chapB; chapA -> a1, a2; a1 -> shared;
chapB -> b1, shared; b1 -> M1 (Mathlib); a2 -> M1, M2. Constant a1.proof_1 folds into a1 and is the one
referencing `shared`. Expected idom: main=root, chapA=main, chapB=main, a1=chapA, a2=chapA, shared=main,
b1=chapB, t3only=T3.
usage: test_dominators.py WORKDIR
"""
import gzip, os, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = sys.argv[1]
ds, out = os.path.join(W, 'ds'), os.path.join(W, 'out')
os.makedirs(ds, exist_ok=True)
THM = ['riemannHypothesis', 'riemannZeta_eq_zero_re', 'LFunction_ne_zero_of_half_lt_re',
       'LFunction_eq_zero_re', 'LFunction_eq_zero_re_of_isPrimitive']
# name, kind, origin, decl, file, start, end, block
C = [(t, 'theorem', 'project', t, 'src/Main.lean', 2 * i + 1, 2 * i + 1) for i, t in enumerate(THM)]
C += [('main', 'theorem', 'project', 'main', 'src/A/Top.lean', 1, 10),
      ('chapA', 'theorem', 'project', 'chapA', 'src/A/X/a.lean', 1, 5),
      ('chapB', 'theorem', 'project', 'chapB', 'src/B/b.lean', 1, 7),
      ('a1', 'theorem', 'project', 'a1', 'src/A/X/a.lean', 6, 20),
      ('a1.proof_1', 'theorem', 'project', 'a1', 'src/A/X/a.lean', 6, 20),
      ('a2', 'def', 'project', 'a2', 'src/A/Y/c.lean', 1, 3),
      ('shared', 'def', 'project', 'shared', 'src/S/s.lean', 1, 100),
      ('b1', 'theorem', 'project', 'b1', 'src/B/b.lean', 8, 9),
      ('t3only', 'theorem', 'project', 't3only', 'src/A/Top.lean', 11, 12),
      ('a1._proof_2', 'theorem', 'project', 'a1', 'src/A/X/a.lean', 6, 20),
      ('M1', 'theorem', 'mathlib', '', '', 0, 0), ('M2', 'def', 'mathlib', '', '', 0, 0)]
SHARED = {'a1._proof_2'}  # a shared aux lemma generated by a1 and reused by b1: must not make b1 depend on a1
ids = {c[0]: i for i, c in enumerate(C)}
E = [(t, 'main') for t in THM] + [('LFunction_eq_zero_re', 't3only'), ('main', 'chapA'), ('main', 'chapB'),
                                  ('chapA', 'a1'), ('chapA', 'a2'), ('a1', 'a1.proof_1'), ('a1.proof_1', 'shared'),
                                  ('chapB', 'b1'), ('chapB', 'shared'), ('b1', 'M1'), ('a2', 'M1'), ('a2', 'M2'),
                                  ('a1', 'a1._proof_2'), ('b1', 'a1._proof_2')]
mask = {c[0]: 31 for c in C}
mask['t3only'] = 8
with open(os.path.join(ds, 'constants.tsv'), 'w') as f:
    f.write('id\tname\tkind\torigin\tdecl\tfile\tstart_line\tend_line\tblock\ttype_dag\tvalue_dag\tin_cone\tdepth\tthm_mask\tshared_aux\n')
    for i, (nm, k, o, d, fl, s, e) in enumerate(C):
        f.write(f'{i}\t{nm}\t{k}\t{o}\t{d}\t{fl}\t{s if fl else ""}\t{e if fl else ""}\t{i}\t3\t5\t1\t1\t{mask[nm]}\t{"true" if nm in SHARED else "false"}\n')
with open(os.path.join(ds, 'edges.tsv'), 'w') as f:
    f.write('src\tdst\tvia\tsrc_id\tdst_id\n')
    for a, b in E:
        f.write(f'{a}\t{b}\tvalue\t{ids[a]}\t{ids[b]}\n')
with open(os.path.join(ds, 'decls.tsv'), 'w') as f:
    f.write('decl\tkind\torigin\tfile\tstart_line\tend_line\tlines\tin_cone\tgenerated\n')
    seen = set()
    for nm, k, o, d, fl, s, e in C:
        if o == 'project' and d not in seen:
            seen.add(d)
            f.write(f'{d}\t{k}\tproject\t{fl}\t{s}\t{e}\t{e - s + 1}\t1\t{"true" if d == "a2" else "false"}\n')
    f.write('unused\ttheorem\tproject\tsrc/B/b.lean\t20\t30\t11\t0\tfalse\n')

subprocess.run([sys.executable, os.path.join(HERE, 'dominators.py'), ds, out], check=True)
rows = {}
with gzip.open(os.path.join(out, 'dominators.tsv.gz'), 'rt') as f:
    hdr = next(f).rstrip('\n').split('\t')
    for line in f:
        r = dict(zip(hdr, line.rstrip('\n').split('\t')))
        rows[r['decl']] = r
want = {'main': '(root: the five theorems)', 'chapA': 'main', 'chapB': 'main', 'a1': 'chapA', 'a2': 'chapA',
        'shared': 'main', 'b1': 'chapB', 't3only': 'LFunction_eq_zero_re', 'a1._proof_2': 'main'}
for d, p in want.items():
    assert rows[d]['idom'] == p, (d, rows[d]['idom'], p)
assert rows['chapA']['sub_decls'] == '3' and rows['chapA']['sub_lines'] == str(5 + 15 + 3), rows['chapA']
assert rows['a1']['n_constants'] == '2' and rows['a1']['kernel_dag'] == '16', rows['a1']
assert rows['a2']['ext_refs'] == '2' and rows['chapA']['sub_ext_refs'] == '2', rows['a2']
assert rows['main']['sub_decls'] == '8' and rows['main']['sub_lines'] == '142', rows['main']
assert rows['a1._proof_2']['kind'] == 'shared_aux' and rows['a1._proof_2']['lines'] == '0'
assert rows['a2']['node_type'] == 'generated' and rows['a1']['node_type'] == 'decl', (rows['a2'], rows['a1'])
assert 'unused' not in rows
import json
s = json.load(open(os.path.join(out, 'dominators-summary.json')))
assert ', 0 failures' in s['dom_check'], s['dom_check']
assert all(c[3] == 0 for c in s['raw_edge_check_top20'])
assert s['per_theorem']['LFunction_eq_zero_re']['only_this_theorem_decls'] == 1
nk = s['node_kinds']
assert nk['source declarations'] == 12 and nk['generated declarations (made by notation, macro or elab commands)'] == 1, nk
print('dominators.py synthetic test OK')
